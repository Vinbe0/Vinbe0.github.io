const GITHUB_USER = "Vinbe0";
const HIDDEN_REPOS = ["website", "Vinbe0.github.io"];
const localeCodes = { English: "en", Kazakh: "kk", Russian: "ru" };
const recentProjects = document.getElementById("recent-projects");
let repos = [];

const languageSelect = document.getElementById("language");
let dictionary = translations.English;

function t(key) {
    return dictionary[key] || translations.English[key] || key;
}

function updateLanguage(lang) {
    dictionary = translations[lang] || translations.English;

    document.querySelectorAll("[data-i18n]").forEach((node) => {
        const key = node.dataset.i18n;
        if (dictionary[key]) {
            node.textContent = dictionary[key];
        }
    });

    document.documentElement.lang = localeCodes[lang] || "en";
    document.title = t(document.body.dataset.pageTitle || "pageTitle");
    renderProjects();
    document.dispatchEvent(new CustomEvent("sitelanguagechange"));
}

// Some browsers ship without Kazakh month names, so format those by hand.
const kazakhMonths = ["қаң.", "ақп.", "нау.", "сәу.", "мам.", "мау.", "шіл.", "там.", "қыр.", "қаз.", "қар.", "жел."];

function formatDate(value, { day = false } = {}) {
    const date = new Date(value);
    const lang = document.documentElement.lang;

    if (lang === "kk") {
        const month = `${kazakhMonths[date.getMonth()]} ${date.getFullYear()}`;
        return day ? `${date.getDate()} ${month}` : month;
    }

    return new Intl.DateTimeFormat(lang, {
        day: day ? "numeric" : undefined,
        month: "short",
        year: "numeric"
    }).format(date);
}

function renderProjects() {
    if (!recentProjects || repos.length === 0) {
        return;
    }

    const items = repos.map((repo) => {
        const item = document.createElement("li");
        const link = document.createElement("a");
        const label = document.createElement("span");
        const meta = document.createElement("span");

        link.href = repo.html_url;
        link.target = "_blank";
        link.rel = "noreferrer";
        label.className = "row-label";
        label.textContent = repo.name;
        meta.className = "row-meta";
        meta.textContent = [repo.language, formatDate(repo.pushed_at)].filter(Boolean).join(" · ");

        link.append(label, meta);
        item.appendChild(link);
        return item;
    });

    recentProjects.replaceChildren(...items);
}

async function loadProjects() {
    const cacheKey = "repos";

    try {
        const cached = JSON.parse(sessionStorage.getItem(cacheKey));
        if (Array.isArray(cached)) {
            repos = cached;
            renderProjects();
            return;
        }
    } catch (error) {}

    try {
        const response = await fetch(`https://api.github.com/users/${GITHUB_USER}/repos?sort=pushed&per_page=30`);
        if (!response.ok) {
            throw new Error(`GitHub returned ${response.status}`);
        }

        const data = await response.json();
        repos = data
            .filter((repo) => !repo.fork && !HIDDEN_REPOS.includes(repo.name))
            .slice(0, 5)
            .map(({ name, html_url, language, pushed_at }) => ({ name, html_url, language, pushed_at }));

        try {
            sessionStorage.setItem(cacheKey, JSON.stringify(repos));
        } catch (error) {}

        renderProjects();
    } catch (error) {
        // Keep the static list from the HTML if GitHub is unavailable.
        console.warn("Could not load GitHub projects:", error);
    }
}

function initialLanguage() {
    try {
        const saved = localStorage.getItem("language");
        if (translations[saved]) {
            return saved;
        }
    } catch (error) {}

    const browserLanguages = navigator.languages || [navigator.language || ""];
    for (const code of browserLanguages) {
        const base = code.toLowerCase().split("-")[0];
        if (base === "kk") return "Kazakh";
        if (base === "ru") return "Russian";
        if (base === "en") return "English";
    }

    return "Russian";
}

languageSelect.addEventListener("change", (event) => {
    updateLanguage(event.target.value);
    try {
        localStorage.setItem("language", event.target.value);
    } catch (error) {}
});

const bioButtons = document.querySelectorAll("[data-bio]");
const bioPanels = document.querySelectorAll("[data-bio-panel]");

function showBio(length) {
    bioButtons.forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.bio === length));
    });
    bioPanels.forEach((panel) => {
        panel.hidden = panel.dataset.bioPanel !== length;
    });
}

bioButtons.forEach((button) => {
    button.addEventListener("click", () => showBio(button.dataset.bio));
});

const themeToggle = document.getElementById("theme-toggle");
const darkQuery = window.matchMedia("(prefers-color-scheme: dark)");

function activeTheme() {
    return document.documentElement.dataset.theme || (darkQuery.matches ? "dark" : "light");
}

function syncThemeToggle() {
    const theme = activeTheme();
    document.documentElement.dataset.themeActive = theme;
    themeToggle.setAttribute("aria-pressed", String(theme === "dark"));
}

themeToggle.addEventListener("click", () => {
    const next = activeTheme() === "dark" ? "light" : "dark";
    document.documentElement.dataset.theme = next;
    try {
        localStorage.setItem("theme", next);
    } catch (error) {}
    syncThemeToggle();
});

darkQuery.addEventListener("change", syncThemeToggle);
syncThemeToggle();

document.getElementById("year").textContent = new Date().getFullYear();

languageSelect.value = initialLanguage();
updateLanguage(languageSelect.value);
loadProjects();
